USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS DEV_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS DRUG_DB;
CREATE SCHEMA IF NOT EXISTS DRUG_DB.RAW;

USE WAREHOUSE DEV_WH;
USE SCHEMA DRUG_DB.RAW;
SELECT COUNT(*) FROM DRUG_DB.RAW.SHORTAGE;

-- 1. How many entries are there for each status?
SELECT STATUS, COUNT(*) AS N
FROM SHORTAGE
GROUP BY STATUS
ORDER BY N DESC;

--2. Top 10 ingredients with the most shortage reports.
SELECT INGREDIENTS, COUNT(*) AS N
FROM SHORTAGE
GROUP BY INGREDIENTS
ORDER BY N DESC
LIMIT 10;

--3. Number of new shortages starting each month.
SELECT DATE_TRUNC('MONTH', ACTUAL_START_DATE) AS MONTH, COUNT(*) AS N
FROM SHORTAGE
WHERE ACTUAL_START_DATE IS NOT NULL
GROUP BY MONTH
ORDER BY MONTH;

--4. Breakdown of shortages by cause.
SELECT REASON,
       COUNT(*) AS N,
       ROUND(COUNT(*) * 100 / SUM(COUNT(*)) OVER (), 1) AS PCT
FROM SHORTAGE
GROUP BY REASON
ORDER BY N DESC;

--5. Number of days each currently shortage-listed medication has been in shortage.
SELECT BRAND_NAME, COMPANY_NAME, ACTUAL_START_DATE,
       DATEDIFF('DAY', ACTUAL_START_DATE, CURRENT_DATE()) AS DAYS_IN_SHORTAGE
FROM SHORTAGE
WHERE STATUS = 'Actual shortage'
ORDER BY DAYS_IN_SHORTAGE DESC NULLS LAST
LIMIT 20;

